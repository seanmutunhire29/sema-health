/// Static UI strings for Sema, keyed by short identifiers and grouped per
/// language. All translations are best-effort; less-resourced strings fall
/// back to English via [SemaStrings.t]. Marketing copy in Twi, Ga and Yorùbá
/// should be reviewed by a native speaker before release.
library;

class SemaStrings {
  const SemaStrings(this.code, this._map);
  final String code;
  final Map<String, String> _map;

  /// Look up a key. Falls back to English, then to the key itself, so a typo
  /// renders visibly during dev rather than silently as an empty string.
  String t(String key) => _map[key] ?? _en[key] ?? key;

  /// Like [t] with positional `{0}`, `{1}` substitutions.
  String f(String key, [List<String> args = const []]) {
    var s = t(key);
    for (var i = 0; i < args.length; i++) {
      s = s.replaceAll('{$i}', args[i]);
    }
    return s;
  }
}

SemaStrings stringsFor(String code) => SemaStrings(code, _byCode[code] ?? _en);

